//! Running standalone applications inside tuxhub.
//!
//! Wayland does not allow embedding windows of other applications. tuxhub
//! therefore starts an xpra session per tool (its own X display and D-Bus),
//! runs the application in it and shows it through the xpra HTML5 client.
//! Each session runs its own portal services, so file dialogs open on the
//! virtual display, and a watcher maximizes the main window so it fills the
//! available area. All sessions listen on 127.0.0.1 only.

use crate::{Hub, tools};
use serde::Serialize;
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::Duration;
use tauri::{AppHandle, Manager, Runtime};
use tokio::process::{Child, Command};
use tokio::sync::Mutex;

const WATCHER: &str = include_str!("xpra_watch.py");
const PORTALS_CONF: &str = "[preferred]\ndefault=gtk\n";

struct Session {
    display: u32,
    port: u16,
    /// Marker file with the display number, used for cleanup after a crash.
    marker: PathBuf,
    xpra: Child,
    watcher: Option<Child>,
}

#[derive(Default)]
pub struct Sessions(Mutex<HashMap<String, Session>>);

#[derive(Clone, Serialize)]
pub struct EmbedInfo {
    pub url: String,
}

fn which(cmd: &str) -> Option<PathBuf> {
    std::env::var_os("PATH").and_then(|p| {
        std::env::split_paths(&p)
            .map(|d| d.join(cmd))
            .find(|p| p.is_file())
    })
}

/// First existing path; distributions install the portal binaries in different places.
fn first_existing(candidates: &[&str]) -> Option<String> {
    candidates
        .iter()
        .find(|p| Path::new(p).is_file())
        .map(|p| p.to_string())
}

/// Name of the missing dependency for running applications inside tuxhub
/// (`xpra` or `python3`), or `None` when everything is available.
pub fn missing() -> Option<String> {
    ["xpra", "python3"]
        .into_iter()
        .find(|cmd| which(cmd).is_none())
        .map(String::from)
}

fn free_display(taken: &[u32]) -> Option<u32> {
    (110..400).find(|n| {
        !taken.contains(n)
            && !Path::new(&format!("/tmp/.X11-unix/X{n}")).exists()
            && !Path::new(&format!("/tmp/.X{n}-lock")).exists()
    })
}

fn free_port() -> Result<u16, String> {
    std::net::TcpListener::bind("127.0.0.1:0")
        .and_then(|l| l.local_addr())
        .map(|a| a.port())
        .map_err(|e| e.to_string())
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Launch script that runs inside the xpra session.
fn run_script(lc: &tools::LaunchCmd, portal_conf_dir: &Path) -> String {
    let mut s = String::from(
        "#!/bin/sh\n# Generated by tuxhub. Runs inside an xpra session with its own DISPLAY and D-Bus.\n\
         unset WAYLAND_DISPLAY\n\
         export GDK_BACKEND=x11 QT_QPA_PLATFORM=xcb SDL_VIDEODRIVER=x11 WEBKIT_DISABLE_DMABUF_RENDERER=1\n",
    );
    let gtk = first_existing(&[
        "/usr/libexec/xdg-desktop-portal-gtk",
        "/usr/lib/xdg-desktop-portal-gtk",
        "/usr/lib/x86_64-linux-gnu/xdg-desktop-portal-gtk",
    ]);
    let portal = first_existing(&[
        "/usr/libexec/xdg-desktop-portal",
        "/usr/lib/xdg-desktop-portal",
        "/usr/lib/x86_64-linux-gnu/xdg-desktop-portal",
    ]);
    if let (Some(gtk), Some(portal)) = (gtk, portal) {
        s += &format!(
            "{gtk} >/dev/null 2>&1 &\nsleep 0.5\n\
             XDG_CONFIG_DIRS={}:\"${{XDG_CONFIG_DIRS:-/etc/xdg}}\" {portal} --replace >/dev/null 2>&1 &\nsleep 1\n",
            sh_quote(&portal_conf_dir.to_string_lossy())
        );
    }
    if let Some(cwd) = &lc.cwd {
        s += &format!("cd {}\n", sh_quote(&cwd.to_string_lossy()));
    }
    let mut args: Vec<String> = lc.args.clone();
    if lc.flatpak {
        // Force Flatpak applications onto X11, otherwise they open on the Wayland desktop.
        let id = args.pop().unwrap_or_default();
        args.extend(
            [
                "--nosocket=wayland",
                "--socket=x11",
                "--env=GDK_BACKEND=x11",
                "--env=QT_QPA_PLATFORM=xcb",
            ]
            .map(String::from),
        );
        args.push(id);
    }
    s += "exec ";
    s += &sh_quote(&lc.program.to_string_lossy());
    for a in &args {
        s += " ";
        s += &sh_quote(a);
    }
    s += "\n";
    s
}

/// The xpra web client is bundled with the user interface (`static/xpra`) and
/// loaded from the same origin. As a cross-origin iframe, WebKitGTK denies it
/// access to sessionStorage and the client fails to start.
fn url(port: u16) -> String {
    format!(
        "/xpra/index.html?server=127.0.0.1&port={port}&ssl=false&floating_menu=false&sound=false"
    )
}

pub async fn start<R: Runtime>(app: &AppHandle<R>, id: &str) -> Result<EmbedInfo, String> {
    if let Some(dep) = missing() {
        return Err(format!("{dep} is not installed"));
    }
    let hub = app.state::<Hub>();
    let mut sessions = hub.embeds.0.lock().await;
    if let Some(s) = sessions.get_mut(id) {
        if matches!(s.xpra.try_wait(), Ok(None)) {
            return Ok(EmbedInfo { url: url(s.port) });
        }
        sessions.remove(id);
    }

    let inst = tools::load(&hub.tools_dir, id)?;
    let lc = tools::launch_cmd(&hub.tools_dir, &inst)?;
    let base = hub
        .tools_dir
        .parent()
        .unwrap_or(&hub.tools_dir)
        .join("embed");
    let dir = base.join(id);
    let conf = base.join("portalconf");
    std::fs::create_dir_all(conf.join("xdg-desktop-portal")).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(conf.join("xdg-desktop-portal/portals.conf"), PORTALS_CONF)
        .map_err(|e| e.to_string())?;
    let watcher_py = base.join("xpra_watch.py");
    std::fs::write(&watcher_py, WATCHER).map_err(|e| e.to_string())?;
    let run_sh = dir.join("run.sh");
    std::fs::write(&run_sh, run_script(&lc, &conf)).map_err(|e| e.to_string())?;
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(&run_sh, std::fs::Permissions::from_mode(0o755))
        .map_err(|e| e.to_string())?;

    let taken: Vec<u32> = sessions.values().map(|s| s.display).collect();
    let display = free_display(&taken).ok_or("no free X display found")?;
    let port = free_port()?;
    let log = std::fs::File::create(dir.join("xpra.log")).map_err(|e| e.to_string())?;
    let log2 = log.try_clone().map_err(|e| e.to_string())?;

    let xpra = Command::new("xpra")
        .arg("start")
        .arg(format!(":{display}"))
        .arg("--daemon=no")
        .arg(format!("--bind-tcp=127.0.0.1:{port}"))
        .arg("--html=off")
        .arg(format!("--start-child={}", run_sh.display()))
        .args([
            "--exit-with-children=yes",
            // Allow several clients. Otherwise each new client disconnects the
            // previous one and two views keep reconnecting each other.
            "--sharing=yes",
            "--dbus=yes",
            "--mdns=no",
            "--pulseaudio=no",
            "--notifications=no",
            "--systemd-run=no",
            "--webcam=no",
            "--printing=no",
            "--file-transfer=no",
            "--tray=no",
            "--splash=no",
        ])
        .stdin(Stdio::null())
        .stdout(log)
        .stderr(log2)
        .kill_on_drop(true)
        .spawn()
        .map_err(|e| format!("could not start xpra: {e}"))?;
    let marker = dir.join("session");
    let _ = std::fs::write(&marker, display.to_string());
    let mut session = Session {
        display,
        port,
        marker,
        xpra,
        watcher: None,
    };

    // Wait until the session accepts connections.
    let mut ready = false;
    for _ in 0..80 {
        if tokio::net::TcpStream::connect(("127.0.0.1", port))
            .await
            .is_ok()
        {
            ready = true;
            break;
        }
        if !matches!(session.xpra.try_wait(), Ok(None)) {
            break;
        }
        tokio::time::sleep(Duration::from_millis(250)).await;
    }
    if !ready {
        let _ = session.xpra.kill().await;
        return Err(format!(
            "the session did not start, see {}",
            dir.join("xpra.log").display()
        ));
    }

    session.watcher = Command::new("python3")
        .arg(&watcher_py)
        .arg(format!(":{display}"))
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .kill_on_drop(true)
        .spawn()
        .ok();
    sessions.insert(id.to_string(), session);
    Ok(EmbedInfo { url: url(port) })
}

pub async fn status<R: Runtime>(app: &AppHandle<R>, id: &str) -> Option<EmbedInfo> {
    let hub = app.state::<Hub>();
    let mut sessions = hub.embeds.0.lock().await;
    let s = sessions.get_mut(id)?;
    if matches!(s.xpra.try_wait(), Ok(None)) {
        Some(EmbedInfo { url: url(s.port) })
    } else {
        // The application was closed, so the session ended by itself.
        sessions.remove(id);
        None
    }
}

pub async fn stop<R: Runtime>(app: &AppHandle<R>, id: &str) {
    let session = app.state::<Hub>().embeds.0.lock().await.remove(id);
    if let Some(s) = session {
        shutdown(s).await;
    }
}

pub async fn stop_all<R: Runtime>(app: &AppHandle<R>) {
    let all: Vec<Session> = app
        .state::<Hub>()
        .embeds
        .0
        .lock()
        .await
        .drain()
        .map(|(_, s)| s)
        .collect();
    for s in all {
        shutdown(s).await;
    }
}

/// At startup, stops sessions left behind by a previous tuxhub process (after a
/// crash, for example). Only displays recorded in tuxhub's own marker files
/// are affected.
pub async fn cleanup_stale(embed_dir: &Path) {
    // Only sessions older than this process, never one that is just starting.
    let hub_start = std::time::SystemTime::now();
    let Ok(rd) = std::fs::read_dir(embed_dir) else {
        return;
    };
    for entry in rd.flatten() {
        let marker = entry.path().join("session");
        let older = std::fs::metadata(&marker)
            .and_then(|m| m.modified())
            .is_ok_and(|t| t < hub_start);
        if !older {
            continue;
        }
        let Some(display) = std::fs::read_to_string(&marker)
            .ok()
            .and_then(|s| s.trim().parse::<u32>().ok())
        else {
            continue;
        };
        let _ = tokio::time::timeout(
            Duration::from_secs(8),
            Command::new("xpra")
                .arg("stop")
                .arg(format!(":{display}"))
                .output(),
        )
        .await;
        let _ = std::fs::remove_file(marker);
    }
}

async fn shutdown(mut s: Session) {
    let _ = std::fs::remove_file(&s.marker);
    // Stop gracefully (cleans up the display and children), otherwise kill.
    let _ = tokio::time::timeout(
        Duration::from_secs(5),
        Command::new("xpra")
            .arg("stop")
            .arg(format!(":{}", s.display))
            .output(),
    )
    .await;
    if tokio::time::timeout(Duration::from_secs(3), s.xpra.wait())
        .await
        .is_err()
    {
        let _ = s.xpra.kill().await;
    }
    if let Some(mut w) = s.watcher {
        let _ = w.kill().await;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lc(flatpak: bool) -> tools::LaunchCmd {
        if flatpak {
            tools::LaunchCmd {
                program: "flatpak".into(),
                args: vec!["run".into(), "net.lutris.Lutris".into()],
                cwd: None,
                flatpak: true,
            }
        } else {
            tools::LaunchCmd {
                program: "/opt/my app/it's.AppImage".into(),
                args: vec!["--flag".into()],
                cwd: Some("/opt/my app".into()),
                flatpak: false,
            }
        }
    }

    #[test]
    fn script_quotes_and_forces_x11() {
        let s = run_script(&lc(false), Path::new("/tmp/conf"));
        assert!(s.contains("unset WAYLAND_DISPLAY"));
        assert!(s.contains("cd '/opt/my app'"));
        assert!(s.contains(r"exec '/opt/my app/it'\''s.AppImage' '--flag'"));

        let f = run_script(&lc(true), Path::new("/tmp/conf"));
        assert!(f.contains("'run' '--nosocket=wayland' '--socket=x11'"));
        assert!(f.trim_end().ends_with("'net.lutris.Lutris'"));
    }

    /// Runs the installed GIF Color Changer inside tuxhub. Requires xpra and the
    /// installed tool: `cargo test -- --ignored embed_real`
    #[tokio::test]
    #[ignore]
    async fn embed_real_app() {
        let home = std::env::var("HOME").unwrap();
        let real_tools = PathBuf::from(home).join(".local/share/io.github.sirsnolte.tuxhub/tools");
        let app = tauri::test::mock_app();
        let base = std::env::temp_dir().join(format!("tuxhub-embed-{}", std::process::id()));
        let tools_dir = base.join("tools");
        std::fs::create_dir_all(&tools_dir).unwrap();
        // Copy only tool.json; the files stay in place.
        let inst = tools::load(&real_tools, "gif-color-changer")
            .expect("GIF Color Changer must be installed");
        let root = inst.root_dir(&real_tools).unwrap();
        let link = tools_dir.join("gif-color-changer");
        std::fs::create_dir_all(&link).unwrap();
        std::os::unix::fs::symlink(
            real_tools.join("gif-color-changer/files"),
            link.join("files"),
        )
        .unwrap();
        std::fs::copy(
            real_tools.join("gif-color-changer/tool.json"),
            link.join("tool.json"),
        )
        .unwrap();
        assert!(root.exists());
        app.manage(crate::Hub::for_test(tools_dir, base.join("settings")));

        let info = start(app.handle(), "gif-color-changer")
            .await
            .expect("session starts");
        println!("URL: {}", info.url);
        assert!(
            info.url
                .starts_with("/xpra/index.html?server=127.0.0.1&port=")
        );
        let port: u16 = info
            .url
            .split("port=")
            .nth(1)
            .unwrap()
            .split('&')
            .next()
            .unwrap()
            .parse()
            .unwrap();
        assert!(
            tokio::net::TcpStream::connect(("127.0.0.1", port))
                .await
                .is_ok(),
            "session is reachable"
        );
        assert!(status(app.handle(), "gif-color-changer").await.is_some());
        if std::env::var("TUXHUB_KEEP").is_ok() {
            println!("keeping the session open for 60 s");
            tokio::time::sleep(Duration::from_secs(60)).await;
        }
        stop(app.handle(), "gif-color-changer").await;
        assert!(status(app.handle(), "gif-color-changer").await.is_none());
        std::fs::remove_dir_all(base).unwrap();
    }

    #[test]
    fn display_and_port() {
        let d = free_display(&[110, 111]).unwrap();
        assert!(d > 111);
        assert!(free_port().unwrap() > 0);
    }
}
